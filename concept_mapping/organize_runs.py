"""Create chronological run shortcuts and an index without relocating experiment data.

The canonical flat paths are retained for running jobs, checkpoints and reports.
VS Code hides only those flat entries; month folders provide the browsing view.
Refresh with this script. --undo removes only generated shortcuts/settings.
"""
import argparse
import csv
import json
import os
import subprocess
from datetime import datetime
from pathlib import Path
from urllib.parse import quote
from zoneinfo import ZoneInfo

REPOSITORY = Path(__file__).resolve().parents[1]
TOPICS = {
    '00_active': 'Training runs whose recorded process is alive at the last refresh.',
    '01_training': 'Architectures, reward variants, continuation runs and policy comparisons.',
    '02_practice_and_curricula': 'Deliberate practice, rare-event resets, drills and diamond-density curricula.',
    '03_auxiliary_prediction': 'Stone, reward-sign and multi-achievement prediction experiments.',
    '04_world_models_and_search': 'EfficientZero-style models, simulator search, MCTS and PPO learning-rule experiments.',
    '05_value_function_experiments': 'Counterfactuals, collectability, resource valuation, inventory swaps and value plots.',
    '06_representations_and_circuits': 'Achievement grouping, feature analysis and critic-neuron circuits.',
    '07_episode_datasets': 'Canonical collected episode datasets used by subsequent analyses.',
    '08_videos': 'Standalone rollout-video collections; some studies also contain their own videos.',
    '09_smoke_tests_and_benchmarks': 'Small validation, debugging and throughput artifacts.',
    '10_explanations': 'Map-memory walkthroughs and implementation explanations.',
    '11_other': 'Additional artifacts awaiting a more specific category.',
}
GENERATED = {'README.md', 'catalog.csv', 'catalog.json', 'organization_manifest.json'}
MARKER = '<!-- Generated by concept_mapping/organize_runs.py -->'
TIMEZONE = ZoneInfo('America/Los_Angeles')


def category(name):
    n = name.lower()
    if any(word in n for word in ('smoke', 'validation', 'benchmark', '_checks')) or n.endswith('.log'):
        return '09_smoke_tests_and_benchmarks'
    if n.startswith('master_symbolic_'):
        return '07_episode_datasets'
    if 'video' in n:
        return '08_videos'
    if n.startswith(('map_update_walkthrough', 'spatial_map_memory_implementation')):
        return '10_explanations'
    if any(word in n for word in ('clustering', 'representation', 'transport_', 'diamond_critic_circuit', 'reward_transition_explorer')) or n.startswith(('ad_ppo_', 'ppo_10b_action', 'ppo_10b_icm')):
        return '06_representations_and_circuits'
    if n.startswith(('stone_outcome_', 'multi_outcome_', 'targeted_outcome_', 'reward_sign_', 'auxiliary_search_')):
        return '03_auxiliary_prediction'
    if n.startswith(('symbolic_ez_', 'oracle_', 'ppo_guided_oracle_', 'ppo_sample_efficiency_leaps_', 'learning_rule_')):
        return '04_world_models_and_search'
    if any(word in n for word in ('practice', 'curriculum', 'cppo', 'diamond_density', 'diamond_skill_drill', 'rare_four')):
        return '02_practice_and_curricula'
    if n.startswith(('classic_', 'lava_only_', 'large_feedforward_', 'gru_', 'ppo_memory_comparison',
                     'spatial_ppo_vs_', 'reward_shaped_architectures', 'rnn_death_penalty_comparison',
                     'actor_scratch_', 'cross_actor_critic_transfer_', 'spatial_map_gru_extend_',
                     'death2_', 'death_penalty2_vs_baseline_')):
        return '01_training'
    if n.startswith(('achievement_progress_', 'arrow_', 'zombie_', 'two_zombies_', 'three_zombies_',
                     'collectability_', 'combat_', 'cow_', 'death_penalty2_', 'diamond_', 'early_late_',
                     'empirical_', 'episode19_', 'food_', 'inventory_', 'iron_', 'lava_', 'plant_',
                     'resource_', 'stone_pickaxe_', 'water_')):
        return '05_value_function_experiments'
    return '11_other'


def read_json(path, default):
    return json.loads(path.read_text()) if path.exists() else default


def recorded_states(source):
    files = [source/'progress.json', *sorted(source.glob('*/progress.json'))] if source.is_dir() else []
    states = []
    active = False
    for path in files:
        try:
            progress = json.loads(path.read_text())
            value = progress.get('state')
            if isinstance(value, str):
                states.append(value)
            pid = progress.get('pid')
            if value == 'training' and isinstance(pid, int):
                try:
                    proc = Path('/proc')/str(pid)
                    command = (proc/'cmdline').read_bytes().replace(b'\0', b' ').decode(errors='replace')
                    active = active or source.name in command and (proc/'stat').read_text().split()[2] != 'Z'
                except (OSError, ValueError):
                    pass
        except (OSError, ValueError):
            continue
    return sorted(set(states)), active


def remove_managed_links(root, old):
    for item in old.get('shortcuts', []):
        link = root/item['path']
        if link.is_symlink() and os.readlink(link) == item['target']:
            link.unlink()


def managed_directories(old):
    return old.get('directories', list(TOPICS) if old else [])


def clean_managed_directories(root, old):
    for name in sorted(managed_directories(old), key=lambda value:len(Path(value).parts), reverse=True):
        directory = root/name
        readme = directory/'README.md'
        if readme.exists() and readme.read_text().startswith(MARKER):
            readme.unlink()
        if directory.is_dir() and not any(directory.iterdir()):
            directory.rmdir()


def creation_times(sources):
    """GNU stat exposes Linux birth times that Python stat may omit."""
    if not sources:
        return {}
    try:
        output = subprocess.check_output(['stat', r'--printf=%W\t%n\0', '--', *map(str, sources)], text=True)
        return {name:int(seconds) for row in output.split('\0') if row
                for seconds, _, name in [row.partition('\t')] if int(seconds)>0}
    except (OSError, ValueError, subprocess.CalledProcessError):
        return {}


def run_date(source, births, cached):
    if source.name in cached and cached[source.name][1] != 'last-modified fallback (approximate)':
        return cached[source.name]
    files = [source/'launch_manifest.json', source/'progress.json', source/'run_manifest.json',
             source/'experiment_metadata.json', source/'metadata.json', source/'dataset_metadata.json']
    if source.is_dir():
        for pattern in ('*/progress.json', '*/run_manifest.json', '*/experiment_metadata.json'):
            files.extend(sorted(source.glob(pattern)))
        for path in files:
            if not path.is_file():
                continue
            try:
                data = read_json(path, {})
                keys = ['original_start_time', 'start_time', 'started_at', 'created_at']
                if path.name == 'launch_manifest.json':
                    keys.insert(0, 'time')
                for key in keys:
                    value = data.get(key)
                    if isinstance(value, (int, float)) and not isinstance(value, bool) and value>1000000000:
                        instant = datetime.fromtimestamp(value, TIMEZONE)
                    elif isinstance(value, str):
                        instant = datetime.fromisoformat(value.replace('Z', '+00:00'))
                        if instant.tzinfo is None:
                            continue  # Do not guess the timezone of an unqualified date.
                        instant = instant.astimezone(TIMEZONE)
                    else:
                        continue
                    return instant.date().isoformat(), f'{path.relative_to(source).as_posix()}:{key}'
            except (OSError, ValueError, TypeError, OverflowError, AttributeError):
                continue
    timestamp = births.get(str(source))
    return (datetime.fromtimestamp(timestamp or source.stat().st_mtime, TIMEZONE).date().isoformat(),
            'filesystem creation time' if timestamp else 'last-modified fallback (approximate)')


def update_settings(root, settings, old, sources, undo=False):
    data = read_json(settings, {})
    excludes = data.setdefault('files.exclude', {})
    for key, previous in old.get('settings_changes', {}).items():
        if excludes.get(key) is True:
            if previous['existed']:
                excludes[key] = previous['value']
            else:
                excludes.pop(key, None)
    changes = {}
    if not undo:
        for source in sources:
            key = source.relative_to(REPOSITORY).as_posix()
            if excludes.get(key) is True:
                continue
            changes[key] = {'existed': key in excludes, 'value': excludes.get(key)}
            excludes[key] = True
    if not excludes:
        data.pop('files.exclude', None)
    settings.parent.mkdir(exist_ok=True)
    settings.write_text(json.dumps(data, indent=2)+'\n')
    return changes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--undo', action='store_true', help='Remove generated views and restore managed Explorer filters.')
    args = parser.parse_args()
    root = REPOSITORY/'concept_mapping/runs'
    settings = REPOSITORY/'.vscode/settings.json'
    manifest = root/'organization_manifest.json'
    old = read_json(manifest, {})
    # Parse before making changes. Never overwrite unsupported JSON-with-comments settings.
    read_json(settings, {})
    if (root/'README.md').exists() and not (root/'README.md').read_text().startswith(MARKER):
        raise FileExistsError('Preserve the existing runs README before generating a browser.')
    reserved = set(TOPICS) | {Path(name).parts[0] for name in managed_directories(old)}
    sources = sorted((p for p in root.iterdir() if p.name not in reserved and p.name not in GENERATED), key=lambda p:p.name)
    before = {p.name:(p.stat().st_dev, p.stat().st_ino) for p in sources}
    if args.undo:
        remove_managed_links(root, old)
        update_settings(root, settings, old, [], undo=True)
        clean_managed_directories(root, old)
        for name in GENERATED:
            (root/name).unlink(missing_ok=True)
        print('Removed generated views; canonical runs were untouched.')
        return
    shortcuts, catalog = [], []
    births = creation_times(sources)
    cached = {row['name']:(row['date'], row['date_source'])
              for row in read_json(root/'catalog.json', []) if 'date' in row}
    for source in sources:
        date, date_source = run_date(source, births, cached)
        folder = date[:7]
        states, active = recorded_states(source)
        catalog.append(dict(name=source.name, date=date, date_source=date_source, category=category(source.name),
                            canonical_path=source.relative_to(REPOSITORY).as_posix(),
                            browse_path=f'concept_mapping/runs/{folder}/{source.name}',
                            kind='directory' if source.is_dir() else 'file',
                            recorded_states=', '.join(states), active_at_refresh=active))
    catalog.sort(key=lambda row:row['date'], reverse=True)
    directories = set()
    for row in catalog:
        directories.add(row['date'][:7])
    for name in directories:
        top = name.split('/')[0]
        if (root/top).exists() and top not in reserved:
            raise FileExistsError(f'Refusing to overwrite an existing run named {top}')
    remove_managed_links(root, old)
    clean_managed_directories(root, old)
    for row in catalog:
        source = REPOSITORY/row['canonical_path']
        directory = root/row['date'][:7]
        directory.mkdir(parents=True, exist_ok=True)
        link = directory/source.name
        target = os.path.relpath(source, directory)
        if link.exists() or link.is_symlink():
            raise FileExistsError(f'Refusing to overwrite {link}')
        link.symlink_to(target, target_is_directory=source.is_dir())
        shortcuts.append(dict(path=link.relative_to(root).as_posix(), target=target))
    index = [MARKER, '# Experiment runs', '',
             'Browse by **month → run**, with newest dates first in each month’s index. Exact dates use **America/Los_Angeles (Pacific time)** and remain available in the catalog.', '',
             'Dates come from recorded run-start metadata, otherwise filesystem creation time. A last-modified fallback is used only if neither is available and is labeled approximate in the catalog. Chosen dates are retained on refresh so later edits do not move older runs between dates.', '',
             'The date folders contain shortcuts. Original data paths, checkpoints, reports and active jobs retain their existing locations.', '',
             'VS Code hides the flat legacy entries using workspace `files.exclude` settings. They still exist and can be opened by their original paths. No data was moved, copied or deleted.', '',
             '[Full catalog](catalog.csv)', '',
             '| Month | Entries |', '| --- | ---: |']
    months = sorted({row['date'][:7] for row in catalog}, reverse=True)
    for month in months:
        entries = [row for row in catalog if row['date'].startswith(month)]
        index.append(f'| [{month}]({month}/README.md) | {len(entries)} |')
        lines = [MARKER, '# '+month, '', 'Runs are directly inside this month folder. Exact dates are Pacific time; newest dates appear first below.', '',
                 '| Date | Run / artifact | Category | Recorded state |', '| --- | --- | --- | --- |']
        for row in entries:
            lines.append(f'| {row["date"]} | [{row["name"]}](../{quote(row["name"])}) | {row["category"][3:]} | {row["recorded_states"] or "—"} |')
        (root/month/'README.md').write_text('\n'.join(lines)+'\n')
    index += ['', '## Refresh or undo', '',
              'Run `python concept_mapping/organize_runs.py` from the repository root to date new runs and refresh recorded statuses. New runs remain visible at the top level until refreshed.', '',
              'Run `python concept_mapping/organize_runs.py --undo` to remove the generated shortcuts and restore their previous Explorer settings. It does not remove run data.', '',
              'Statuses are a snapshot, not a live monitor. The catalog’s `active_at_refresh` field checks progress metadata and process identity; refresh from the server terminal so its process namespace is visible. Historical recorded states can be stale. `catalog.csv` and `catalog.json` list every canonical entry.']
    (root/'README.md').write_text('\n'.join(index)+'\n')
    (root/'catalog.json').write_text(json.dumps(catalog, indent=2)+'\n')
    with (root/'catalog.csv').open('w') as handle:
        writer = csv.DictWriter(handle, fieldnames=list(catalog[0]))
        writer.writeheader()
        writer.writerows(catalog)
    changes = update_settings(root, settings, old, sources)
    month_counts = {month:sum(row['date'].startswith(month) for row in catalog) for month in months}
    active_count = sum(row['active_at_refresh'] for row in catalog)
    manifest.write_text(json.dumps(dict(version=3, layout='month',timezone=str(TIMEZONE),
                                        directories=sorted(directories),source_entries=len(sources),shortcuts=shortcuts,
                                        settings_changes=changes, counts=month_counts), indent=2)+'\n')
    assert before == {p.name:(p.stat().st_dev,p.stat().st_ino) for p in sources}, 'A canonical entry changed.'
    assert all((root/entry['path']).resolve(strict=True).exists() for entry in shortcuts)
    assert sum(month_counts.values()) == len(sources)
    print(json.dumps(dict(canonical_entries=len(sources), categorized_entries=len(catalog),
                         active_runs=active_count, counts=month_counts,
                         date_sources={reason:sum(row['date_source']==reason for row in catalog) for reason in sorted({row['date_source'] for row in catalog})},
                         canonical_inodes_unchanged=True, broken_shortcuts=0), indent=2))


if __name__ == '__main__':
    main()
